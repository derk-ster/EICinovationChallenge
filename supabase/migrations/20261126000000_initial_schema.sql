-- EIC Innovation Challenge — initial schema
--
-- Security model
--   * The website's server talks to Supabase with the service-role key, which
--     is never sent to browsers. The anon key is used only server-side for
--     officer sign-in and student email codes.
--   * Row-level security is enabled on every table. Anonymous visitors have no
--     access to any table. Signed-in officers get read access and narrowly
--     scoped writes through policies, as a second line of defense behind the
--     application's own role checks.
--   * Student files live in a private bucket. Officers open them through
--     short-lived signed URLs generated by the server.

