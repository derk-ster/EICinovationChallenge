create table public.rate_limits (
  key text not null,
  window_start timestamptz not null,
  count integer not null default 0,
  primary key (key, window_start)
);

-- ---------------------------------------------------------------- helper functions
create or replace function public.current_officer_id()
returns uuid language sql stable security definer set search_path = public as $$
  select id from public.officers where user_id = auth.uid() and active limit 1
$$;

create or replace function public.current_officer_role()
returns public.officer_role language sql stable security definer set search_path = public as $$
  select role from public.officers where user_id = auth.uid() and active limit 1
$$;

create or replace function public.check_rate_limit(p_key text, p_limit integer, p_window_seconds integer)
returns boolean language plpgsql security definer set search_path = public as $$
declare
  v_window timestamptz := to_timestamp(floor(extract(epoch from now()) / p_window_seconds) * p_window_seconds);
  v_count integer;
begin
  insert into public.rate_limits as r (key, window_start, count)
  values (p_key, v_window, 1)
  on conflict (key, window_start) do update set count = r.count + 1
  returning count into v_count;
  delete from public.rate_limits where window_start < now() - interval '1 day';
  return v_count <= p_limit;
end
$$;

-- Atomically validates and stores a submission. Raises:
--   EIC01 closed, EIC02 duplicate email, EIC03 invalid upload, EIC04 key reused, EIC05 reference collision
create or replace function public.create_submission(p jsonb)
returns table (submission_id uuid, reference text, replayed boolean)
language plpgsql security definer set search_path = public as $$
#variable_conflict use_column
declare
  s public.competition_settings;
  v_deadline timestamptz;
  v_existing public.submissions;
  v_id uuid;
  v_is_test boolean := coalesce((p ->> 'isTest')::boolean, false);
  v_lead text := lower(p ->> 'leadEmail');
  v_member jsonb;
  v_asset jsonb;
  v_upload public.uploads;
begin
  -- Idempotent replay first, so a retried request after success still gets its reference.
  select * into v_existing from public.submissions where idempotency_key = (p ->> 'idempotencyKey')::uuid;
  if found then
    if v_existing.lead_email <> v_lead then
      raise exception 'Submission key already used' using errcode = 'EIC04';
    end if;
    return query select v_existing.id, v_existing.reference, true;
    return;
  end if;

  -- Server-side availability check (cannot be bypassed by the client).
  select * into s from public.competition_settings where id = 1 for share;
  v_deadline := case
    when s.extension_until is not null and (s.deadline_at is null or s.extension_until > s.deadline_at)
      then s.extension_until else s.deadline_at end;
  if not s.submissions_enabled
     or (s.opens_at is not null and now() < s.opens_at)
     or (v_deadline is not null and now() > v_deadline) then
    raise exception 'Submissions are closed' using errcode = 'EIC01';
  end if;

  -- Duplicate check across every student already in a submission.
  if exists (
    select 1 from public.team_members tm
    where tm.is_test = v_is_test and tm.email in (
      select lower(m ->> 'email') from jsonb_array_elements(p -> 'members') m where m ->> 'email' is not null
    )
  ) then
    raise exception 'Duplicate student' using errcode = 'EIC02';
  end if;

  if exists (select 1 from public.submissions where submissions.reference = p ->> 'reference') then
    raise exception 'Reference collision' using errcode = 'EIC05';
  end if;

  insert into public.submissions (
    reference, idempotency_key, entry_type, lead_email, email_verified,
    project_name, description, problem, solution, target_audience, category,
    ai_used, ai_tools, ai_contribution, ai_none_confirmed,
    rules_version, publication_permission, flags, is_test, ip_hash, owner_token_hash
  ) values (
    p ->> 'reference', (p ->> 'idempotencyKey')::uuid, (p ->> 'entryType')::public.entry_type, v_lead,
    coalesce((p ->> 'emailVerified')::boolean, false),
    p ->> 'projectName', p ->> 'description', p ->> 'problem', p ->> 'solution', p ->> 'targetAudience', p ->> 'category',
    (p ->> 'aiUsed')::boolean, p ->> 'aiTools', p ->> 'aiContribution', coalesce((p ->> 'aiNoneConfirmed')::boolean, false),
    p ->> 'rulesVersion', coalesce((p ->> 'publicationPermission')::boolean, false),
    coalesce(array(select jsonb_array_elements_text(p -> 'flags')), '{}'), v_is_test, p ->> 'ipHash', p ->> 'ownerTokenHash'
  ) returning id into v_id;

  for v_member in select * from jsonb_array_elements(p -> 'members') loop
    insert into public.team_members (submission_id, position, full_name, grade, email, is_test)
    values (
      v_id, (v_member ->> 'position')::smallint, v_member ->> 'fullName', (v_member ->> 'grade')::smallint,
      nullif(lower(v_member ->> 'email'), ''), v_is_test
    );
  end loop;

  for v_asset in select * from jsonb_array_elements(p -> 'assets') loop
    if v_asset ->> 'source' = 'file' then
      select * into v_upload from public.uploads where id = (v_asset ->> 'uploadId')::uuid for update;
      if not found
         or v_upload.status <> 'uploaded'
         or v_upload.kind::text <> v_asset ->> 'kind'
         or v_upload.owner_token_hash <> p ->> 'ownerTokenHash'
         or v_upload.is_test <> v_is_test then
        raise exception 'Invalid upload for %', v_asset ->> 'kind' using errcode = 'EIC03';
      end if;
      update public.uploads set status = 'attached' where id = v_upload.id;
      insert into public.submission_assets (submission_id, kind, source, upload_id, duration_status)
      values (v_id, (v_asset ->> 'kind')::public.asset_kind, 'file', v_upload.id, (v_asset ->> 'durationStatus')::public.duration_status);
    else
      insert into public.submission_assets (submission_id, kind, source, url, duration_status)
      values (v_id, (v_asset ->> 'kind')::public.asset_kind, 'link', v_asset ->> 'url', (v_asset ->> 'durationStatus')::public.duration_status);
    end if;
  end loop;

  return query select v_id, p ->> 'reference', false;
exception
  when unique_violation then
    -- Two simultaneous requests for the same student: the unique index wins.
    raise exception 'Duplicate student' using errcode = 'EIC02';
end
$$;

-- Only the server (service role) may call these.
revoke all on function public.check_rate_limit(text, integer, integer) from public, anon, authenticated;
revoke all on function public.create_submission(jsonb) from public, anon, authenticated;
grant execute on function public.check_rate_limit(text, integer, integer) to service_role;
grant execute on function public.create_submission(jsonb) to service_role;

