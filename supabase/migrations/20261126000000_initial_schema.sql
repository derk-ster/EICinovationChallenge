-- Anonymous visitors: no policies → no access to any table.

create policy "officers read officers" on public.officers
  for select to authenticated using (public.current_officer_id() is not null);

create policy "officers read settings" on public.competition_settings
  for select to authenticated using (public.current_officer_id() is not null);
create policy "admins update settings" on public.competition_settings
  for update to authenticated using (public.current_officer_role() = 'admin') with check (public.current_officer_role() = 'admin');

create policy "officers read announcements" on public.announcements
  for select to authenticated using (public.current_officer_id() is not null);
create policy "admins manage announcements" on public.announcements
  for all to authenticated using (public.current_officer_role() = 'admin') with check (public.current_officer_role() = 'admin');

create policy "officers read submissions" on public.submissions
  for select to authenticated using (public.current_officer_id() is not null);
create policy "officers review eligibility" on public.submissions
  for update to authenticated using (public.current_officer_id() is not null) with check (public.current_officer_id() is not null);

create policy "officers read members" on public.team_members
  for select to authenticated using (public.current_officer_id() is not null);
create policy "officers read assets" on public.submission_assets
  for select to authenticated using (public.current_officer_id() is not null);
create policy "officers read uploads" on public.uploads
  for select to authenticated using (public.current_officer_id() is not null);

-- Independent judging: judges see and write only their own sheets; admins see all.
create policy "judges read own scores" on public.scores
  for select to authenticated using (judge_id = public.current_officer_id() or public.current_officer_role() = 'admin');
create policy "judges insert own scores" on public.scores
  for insert to authenticated with check (judge_id = public.current_officer_id());
create policy "judges update own scores" on public.scores
  for update to authenticated using (judge_id = public.current_officer_id()) with check (judge_id = public.current_officer_id());

create policy "admins read audit" on public.audit_log
  for select to authenticated using (public.current_officer_role() = 'admin');

