-- ---------------------------------------------------------------- officers
create table public.officers (
  id uuid primary key default gen_random_uuid(),
  user_id uuid unique references auth.users (id) on delete set null,
  email text not null unique check (email = lower(email)),
  display_name text not null check (char_length(display_name) between 1 and 80),
  role public.officer_role not null default 'judge',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------- settings (single row)
create table public.competition_settings (
  id smallint primary key default 1 check (id = 1),
  submissions_enabled boolean not null default false,
  opens_at timestamptz,
  deadline_at timestamptz,
  extension_until timestamptz,
  extension_note text check (char_length(extension_note) <= 300),
  announced_at timestamptz,
  winner_announcement_at timestamptz,
  allowed_email_domains text[] not null default '{}',
  require_email_verification boolean not null default true,
  min_judges_per_entry integer not null default 2 check (min_judges_per_entry between 1 and 20),
  results_finalized_at timestamptz,
  updated_at timestamptz,
  updated_by uuid references public.officers (id) on delete set null
);
insert into public.competition_settings (id) values (1) on conflict do nothing;

create table public.announcements (
  id uuid primary key default gen_random_uuid(),
  title text not null check (char_length(title) between 1 and 120),
  body text not null check (char_length(body) between 1 and 2000),
  published boolean not null default false,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  created_by uuid references public.officers (id) on delete set null
);

-- ---------------------------------------------------------------- submissions
create table public.submissions (
  id uuid primary key default gen_random_uuid(),
  reference text not null unique check (reference ~ '^EIC-[2-9A-HJKMNP-Z]{6}$'),
  idempotency_key uuid not null unique,
  entry_type public.entry_type not null,
  lead_email text not null check (lead_email = lower(lead_email)),
  email_verified boolean not null default false,
  project_name text not null check (char_length(project_name) between 2 and 80),
  description text not null check (char_length(description) between 20 and 400),
  problem text not null check (char_length(problem) between 20 and 1200),
  solution text not null check (char_length(solution) between 20 and 1200),
  target_audience text not null check (char_length(target_audience) between 5 and 600),
  category text not null check (category in (
    'physical-product', 'website-app', 'business-startup', 'service', 'software-tool', 'improvement'
  )),
  ai_used boolean not null,
  ai_tools text check (char_length(ai_tools) <= 300),
  ai_contribution text check (char_length(ai_contribution) <= 1500),
  ai_none_confirmed boolean not null default false,
  rules_agreed_at timestamptz not null default now(),
  rules_version text not null,
  publication_permission boolean not null default false,
  eligibility public.eligibility_status not null default 'pending',
  eligibility_note text check (char_length(eligibility_note) <= 1000),
  eligibility_reviewed_by uuid references public.officers (id) on delete set null,
  eligibility_reviewed_at timestamptz,
  flags text[] not null default '{}',
  is_test boolean not null default false,
  ip_hash text,
  owner_token_hash text not null,
  submitted_at timestamptz not null default now(),
  constraint ai_disclosure_complete check (
    (ai_used and ai_tools is not null and ai_contribution is not null)
    or (not ai_used and ai_none_confirmed)
  )
);
create index submissions_submitted_at_idx on public.submissions (submitted_at desc);
create index submissions_eligibility_idx on public.submissions (eligibility);

create table public.team_members (
  id uuid primary key default gen_random_uuid(),
  submission_id uuid not null references public.submissions (id) on delete cascade,
  position smallint not null check (position in (1, 2)),
  full_name text not null check (char_length(full_name) between 2 and 80),
  grade smallint not null check (grade between 9 and 12),
  email text check (email = lower(email)),
  is_test boolean not null default false,
  unique (submission_id, position)
);
-- A student (by email) can appear in only one submission: enforces
-- "one submission per student or team" and the two-person team limit.
create unique index team_members_email_unique on public.team_members (email, is_test) where email is not null;

create table public.uploads (
  id uuid primary key default gen_random_uuid(),
  kind public.asset_kind not null,
  storage_path text not null unique,
  file_name text not null check (char_length(file_name) <= 200),
  mime_type text not null,
  declared_size bigint not null check (declared_size > 0),
  actual_size bigint,
  client_duration_seconds numeric(8, 2),
  owner_token_hash text not null,
  status public.upload_status not null default 'pending',
  is_test boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.submission_assets (
  id uuid primary key default gen_random_uuid(),
  submission_id uuid not null references public.submissions (id) on delete cascade,
  kind public.asset_kind not null,
  source public.asset_source not null,
  upload_id uuid references public.uploads (id) on delete restrict,
  url text check (url is null or (url ~ '^https://' and char_length(url) <= 2048)),
  duration_status public.duration_status not null default 'not_applicable',
  unique (submission_id, kind),
  constraint asset_source_matches check (
    (source = 'file' and upload_id is not null and url is null)
    or (source = 'link' and url is not null and upload_id is null)
  )
);

-- ---------------------------------------------------------------- judging
create table public.scores (
  id uuid primary key default gen_random_uuid(),
  submission_id uuid not null references public.submissions (id) on delete cascade,
  judge_id uuid not null references public.officers (id) on delete cascade,
  innovation smallint check (innovation between 0 and 20),
  problem_solution smallint check (problem_solution between 0 and 20),
  prototype_execution smallint check (prototype_execution between 0 and 20),
  business_potential smallint check (business_potential between 0 and 20),
  presentation smallint check (presentation between 0 and 10),
  research smallint check (research between 0 and 10),
  total smallint generated always as (
    coalesce(innovation, 0) + coalesce(problem_solution, 0) + coalesce(prototype_execution, 0)
    + coalesce(business_potential, 0) + coalesce(presentation, 0) + coalesce(research, 0)
  ) stored,
  comments text check (char_length(comments) <= 3000),
  status public.score_status not null default 'draft',
  updated_at timestamptz not null default now(),
  unique (submission_id, judge_id),
  constraint submitted_scores_complete check (
    status = 'draft' or (
      innovation is not null and problem_solution is not null and prototype_execution is not null
      and business_potential is not null and presentation is not null and research is not null
    )
  )
);

